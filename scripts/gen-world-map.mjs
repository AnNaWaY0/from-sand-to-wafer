// Builds src/data/worldPaths.ts from Natural Earth 110m (world-atlas, public domain).
// Equirectangular projection, Antarctica dropped, viewBox 0 0 360 160 (lat 85..-75).
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoPath, geoEquirectangular } from 'd3-geo';
const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/countries-110m.json', import.meta.url)));
const fc = feature(topo, topo.objects.countries);
const W = 360, LAT_TOP = 85, LAT_BOT = -75;
const k = W / 360; // 1 unit per degree
const proj = geoEquirectangular().scale(180 / Math.PI * k).translate([W / 2, LAT_TOP * k]).precision(0.1);
const path = geoPath(proj);
const round = (d) => d.replace(/(\d+\.\d{2})\d+/g, '$1');
const out = {};
for (const f of fc.features) {
  if (f.properties.name === 'Antarctica') continue;
  const d = path(f); if (!d) continue;
  out[String(f.id ?? f.properties.name)] = round(d);
}
const body = `// Generated by scripts/gen-world-map.mjs from Natural Earth 110m (public domain). Do not edit.
// Keys are ISO 3166-1 numeric codes. Projection: equirectangular, 1 unit = 1 degree, top = ${LAT_TOP}°N.
export const WORLD_VIEWBOX = { width: ${W}, height: ${(LAT_TOP - LAT_BOT) * k}, latTop: ${LAT_TOP} } as const;
export const WORLD_PATHS: Record<string, string> = ${JSON.stringify(out)};
`;
writeFileSync(new URL('../src/data/worldPaths.ts', import.meta.url), body);
console.log('countries', Object.keys(out).length, 'bytes', body.length);
